class LLMDiagnoser:
    """Configurable AI-assisted diagnoser supporting external LLMs with safe fallback."""

    __test__ = False

    def __init__(
        self,
        api_key: Optional[str] = None,
        base_url: Optional[str] = None,
        model: Optional[str] = None,
        timeout: float = 15.0,
    ):
        self.api_key = (
            api_key
            or os.getenv("LLM_API_KEY")
            or os.getenv("OPENAI_API_KEY")
            or os.getenv("GEMINI_API_KEY")
        )
        self.base_url = (base_url or os.getenv("LLM_BASE_URL", "https://api.openai.com/v1")).rstrip("/")
        self.model = model or os.getenv("LLM_MODEL", "gpt-4o-mini")
        self.timeout = timeout

    @property
    def is_configured(self) -> bool:
        """True if an API key is present."""
        return bool(self.api_key and len(self.api_key.strip()) > 0)

    def diagnose(
        self,
        finding: BugFinding,
        verification: Optional[VerificationResult] = None,
        minimization: Optional[MinimizationResult] = None,
    ) -> AIDiagnosis:
        """Generate a diagnostic report using an LLM if configured, otherwise fallback cleanly."""
        if not self.is_configured:
            logger.info("No LLM API key configured. Using deterministic rule-based diagnosis.")
            return RuleBasedDiagnoser.diagnose_finding(
                finding=finding,
                verification=verification,
                minimization=minimization,
            )

        prompt_data = self._build_prompt_payload(finding, verification, minimization)

        try:
            with httpx.Client(timeout=self.timeout) as client:
                headers = {
                    "Authorization": f"Bearer {self.api_key}",
                    "Content-Type": "application/json",
                }
                body = {
                    "model": self.model,
                    "messages": [
                        {
                            "role": "system",
                            "content": (
                                "You are an expert API security and software testing engineer. "
                                "Analyze the provided API defect finding and execution traces. "
                                "Return ONLY a valid JSON object matching this schema:\n"
                                "{\n"
                                '  "hypothesis": "string explanation of root cause (labeled as hypothesis)",\n'
                                '  "supporting_evidence": ["list of strings"],\n'
                                '  "additional_checks": ["list of strings"],\n'
                                '  "suggested_fix": "python code snippet",\n'
                                '  "remediation_explanation": "string",\n'
                                '  "uncertainties": ["list of strings"]\n'
                                "}\n"
                                "Do not invent evidence or claim to have inspected internal code you were not given."
                            ),
                        },
                        {"role": "user", "content": json.dumps(prompt_data, indent=2)},
                    ],
                    "response_format": {"type": "json_object"},
                    "temperature": 0.2,
                }
                resp = client.post(f"{self.base_url}/chat/completions", headers=headers, json=body)
                resp.raise_for_status()
                result_json = resp.json()
                raw_text = result_json["choices"][0]["message"]["content"]
                parsed = json.loads(raw_text)

                return AIDiagnosis(
                    hypothesis=parsed.get("hypothesis", "AI diagnostic hypothesis"),
                    supporting_evidence=parsed.get("supporting_evidence", []),
                    additional_checks=parsed.get("additional_checks", []),
                    suggested_fix=parsed.get("suggested_fix", "# Code fix"),
                    remediation_explanation=parsed.get("remediation_explanation", ""),
                    uncertainties=parsed.get("uncertainties", []),
                    is_ai_generated=True,
                    diagnosis_source=self.model,
                )

        except Exception as exc:
            logger.warning("LLM call failed (%s). Falling back to rule-based diagnosis.", exc)
            fallback = RuleBasedDiagnoser.diagnose_finding(finding, verification, minimization)
            fallback.uncertainties.append(f"LLM diagnostic call failed with exception: {exc}")
            return fallback

    @classmethod
    def _build_prompt_payload(
        cls,
        finding: BugFinding,
        verification: Optional[VerificationResult],
        minimization: Optional[MinimizationResult],
    ) -> Dict[str, Any]:
        """Construct sanitized JSON payload for the LLM prompt."""
        payload: Dict[str, Any] = {
            "bug_type": finding.bug_type,
            "severity": finding.severity,
            "endpoint": f"{finding.method} {finding.endpoint}",
            "explanation": finding.explanation,
            "expected_behavior": finding.expected_behavior,
            "actual_response": finding.actual_response,
            "evidence": finding.evidence,
        }
        if verification:
            payload["verification_status"] = verification.status
            payload["is_reproducible"] = verification.is_reproducible
            payload["runs_evaluated"] = verification.runs_evaluated
        if minimization:
            payload["original_request_count"] = minimization.original_request_count
            payload["minimized_request_count"] = minimization.minimized_request_count
            payload["reduction_percentage"] = minimization.reduction_percentage
            payload["pruned_requests"] = minimization.removed_step_names
            payload["pruned_payload_fields"] = minimization.removed_payload_fields

        return payload


