class AIDiagnosis(BaseModel):
    """Structured root cause hypothesis and remediation guidance."""

    __test__ = False  # Prevent pytest from collecting this class as a test suite

    hypothesis: str = Field(
        ...,
        description="Plain-language explanation of the likely root cause (labeled as hypothesis)",
    )
    supporting_evidence: List[str] = Field(
        default_factory=list,
        description="Factual observations and execution traces supporting this hypothesis",
    )
    additional_checks: List[str] = Field(
        default_factory=list,
        description="Recommended inspections or tests to confirm or reject the hypothesis",
    )
    suggested_fix: str = Field(
        ...,
        description="Actionable code fix snippet adapting to project structure",
    )
    remediation_explanation: str = Field(
        ...,
        description="Explanation of how the proposed fix resolves the underlying defect",
    )
    uncertainties: List[str] = Field(
        default_factory=list,
        description="Acknowledged limitations, unverified assumptions, or remaining unknowns",
    )
    is_ai_generated: bool = Field(
        default=False,
        description="True if produced by an active LLM call; False if generated by deterministic fallback",
    )
    diagnosis_source: str = Field(
        default="rule_based_fallback",
        description="Model identifier (e.g. 'gpt-4o-mini', 'gemini-1.5-flash') or fallback tag",
    )


