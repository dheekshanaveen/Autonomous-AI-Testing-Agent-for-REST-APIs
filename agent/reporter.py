class BugReport(BaseModel):
    """Complete structured bug report exportable to Markdown and JSON."""

    __test__ = False

    report_id: str = Field(default_factory=lambda: f"report-{uuid.uuid4().hex[:8]}")
    finding_id: str = Field(...)
    bug_type: str = Field(...)
    severity: str = Field(...)
    endpoint: str = Field(...)
    method: str = Field(...)
    title: str = Field(...)
    summary_explanation: str = Field(...)
    expected_behavior: str = Field(...)
    actual_behavior: str = Field(...)
    evidence: Dict[str, Any] = Field(default_factory=dict)
    verification_status: str = Field(default="CONFIRMED_REPRODUCIBLE")
    is_reproducible: bool = Field(default=True)
    diagnosis: AIDiagnosis
    original_requests_count: int = Field(default=0)
    minimized_requests_count: int = Field(default=0)
    reduction_percentage: float = Field(default=0.0)
    pruned_requests: List[str] = Field(default_factory=list)
    pruned_payload_fields: List[str] = Field(default_factory=list)
    curl_reproduction: str = Field(default="")
    powershell_reproduction: str = Field(default="")
    pytest_reproduction: str = Field(default="")
    created_at: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat(),
    )

    def to_markdown(self) -> str:
        """Render the complete bug report in professional GitHub Flavored Markdown."""
        ai_tag = "Active LLM Model" if self.diagnosis.is_ai_generated else "Rule-Based Deterministic Engine"
        lines = [
            f"# Security Bug Report: {self.title}",
            "",
            f"**Report ID:** `{self.report_id}`  ",
            f"**Finding ID:** `{self.finding_id}`  ",
            f"**Classification:** `{self.bug_type}`  ",
            f"**Severity:** **{self.severity}**  ",
            f"**Endpoint:** `{self.method} {self.endpoint}`  ",
            f"**Status:** `{self.verification_status}` (Reproducible: {self.is_reproducible})  ",
            f"**Diagnosis Source:** {self.diagnosis.diagnosis_source} ({ai_tag})  ",
            f"**Timestamp:** `{self.created_at}`  ",
            "",
            "---",
            "",
            "## 1. Executive Summary",
            "",
            self.summary_explanation,
            "",
            "| Property | Specification / Requirement | Actual Observed Behavior |",
            "| :--- | :--- | :--- |",
            f"| **Behavior** | {self.expected_behavior} | {self.actual_behavior} |",
            "",
            "---",
            "",
            "## 2. Root Cause Hypothesis (AI Diagnosis)",
            "",
            f"> [!IMPORTANT]",
            f"> **Diagnostic Hypothesis:** {self.diagnosis.hypothesis}",
            "",
            "### Supporting Evidence Observed by Agent:",
        ]
        for ev in self.diagnosis.supporting_evidence:
            lines.append(f"- {ev}")

        lines.extend([
            "",
            "### Additional Verifications Recommended:",
        ])
        for chk in self.diagnosis.additional_checks:
            lines.append(f"- [ ] {chk}")

        if self.diagnosis.uncertainties:
            lines.extend([
                "",
                "### Diagnostic Limitations & Uncertainties:",
            ])
            for unc in self.diagnosis.uncertainties:
                lines.append(f"- *{unc}*")

        lines.extend([
            "",
            "---",
            "",
            "## 3. Actionable Code Remediation",
            "",
            self.diagnosis.remediation_explanation,
            "",
            "```python",
            self.diagnosis.suggested_fix,
            "```",
            "",
            "---",
            "",
            "## 4. Test Minimization & Reproduction Steps",
            "",
            f"- **Original Test Sequence:** {self.original_requests_count} requests",
            f"- **Minimized Test Sequence:** {self.minimized_requests_count} requests",
            f"- **Reduction Ratio:** **{self.reduction_percentage:.1f}% reduced**",
            "",
            "### Pruned Redundant Requests:",
        ])
        if self.pruned_requests:
            for pr in self.pruned_requests:
                lines.append(f"- `[-]` {pr}")
        else:
            lines.append("- *(None removed - sequence was already minimal)*")

        if self.pruned_payload_fields:
            lines.extend([
                "",
                "### Pruned Redundant Payload Fields:",
            ])
            for pf in self.pruned_payload_fields:
                lines.append(f"- `[-]` {pf}")

        lines.extend([
            "",
            "---",
            "",
            "## 5. Reproduction Instructions",
            "",
            "### Option A: curl Command Sequence",
            "",
            "```bash",
            self.curl_reproduction,
            "```",
            "",
            "### Option B: Windows PowerShell",
            "",
            "```powershell",
            self.powershell_reproduction,
            "```",
            "",
            "### Option C: Standalone Pytest Test Suite",
            "",
            "Execute independently with: `pytest reports/test_reproduce_bola.py -v`",
            "",
            "```python",
            self.pytest_reproduction,
            "```",
            "",
            "---",
            "",
            "## 6. Collected Evidence Dump",
            "",
            "```json",
            json.dumps(self.evidence, indent=2),
            "```",
        ])
        return "\n".join(lines)

    def to_json(self) -> str:
        """Serialize report to structured JSON."""
        return self.model_dump_json(indent=2)

    def save_to_disk(self, output_dir: str = "reports") -> Tuple[Path, Path, Path]:
        """Save Markdown, JSON, and standalone pytest reproduction files to disk."""
        out_path = Path(output_dir)
        out_path.mkdir(parents=True, exist_ok=True)

        md_file = out_path / f"{self.finding_id}_{self.bug_type.lower()}.md"
        json_file = out_path / f"{self.finding_id}_{self.bug_type.lower()}.json"
        pytest_file = out_path / "test_reproduce_bola.py"

        md_file.write_text(self.to_markdown(), encoding="utf-8")
        json_file.write_text(self.to_json(), encoding="utf-8")
        pytest_file.write_text(self.pytest_reproduction, encoding="utf-8")

        logger.info("Saved reports to: %s, %s, and %s", md_file, json_file, pytest_file)
        return md_file, json_file, pytest_file


