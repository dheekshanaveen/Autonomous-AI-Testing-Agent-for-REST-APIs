class RuleBasedDiagnoser:
    """Provides high-quality deterministic diagnoses when no LLM API key is configured."""

    __test__ = False

    @classmethod
    def diagnose_finding(
        cls,
        finding: BugFinding,
        verification: Optional[VerificationResult] = None,
        minimization: Optional[MinimizationResult] = None,
    ) -> AIDiagnosis:
        """Generate a structured diagnostic hypothesis based on oracle finding classification."""
        bug_type = finding.bug_type

        if bug_type == "BOLA_VIOLATION":
            return AIDiagnosis(
                hypothesis=(
                    f"The endpoint {finding.method} {finding.endpoint} enforces user authentication "
                    "(requiring a valid Bearer token) but omits object-level authorization. "
                    "The backend handler retrieves the requested object by ID and returns it directly "
                    "without verifying that the authenticated user owns or is authorized to view the resource."
                ),
                supporting_evidence=[
                    f"User '{finding.evidence.get('accessor_user_id', 'user-bob')}' successfully accessed "
                    f"private resource '{finding.evidence.get('resource_id', 'ord-1')}' owned by "
                    f"'{finding.evidence.get('resource_owner_id', 'user-alice')}'.",
                    "The server returned HTTP 200 OK with the full private order payload instead of HTTP 403 Forbidden.",
                    "Control test confirmed that the resource owner can access the object normally.",
                    "Reproducibility verification confirmed consistent recurrence across clean resets.",
                ],
                additional_checks=[
                    "Inspect the route handler in 'sample_api/main.py' to confirm if an ownership comparison exists.",
                    "Test unauthenticated access (no Bearer header) to ensure authentication middleware is functioning.",
                    "Test requesting a non-existent ID to ensure 404 handling occurs before authorization logic.",
                ],
                suggested_fix=(
                    '# In sample_api/main.py: get_order_by_id\n'
                    'if order["user_id"] != current_user["user_id"]:\n'
                    '    raise HTTPException(\n'
                    '        status_code=status.HTTP_403_FORBIDDEN,\n'
                    '        detail="Forbidden: You do not have permission to access this order.",\n'
                    '    )'
                ),
                remediation_explanation=(
                    "Before returning private order details, compare the owner ID ('order[\"user_id\"]') "
                    "against the currently authenticated caller ('current_user[\"user_id\"]'). "
                    "If they do not match, reject the request with HTTP 403 Forbidden (or HTTP 404 to prevent ID enumeration)."
                ),
                uncertainties=[
                    "This diagnosis is formulated from black-box HTTP request/response observations and is classified "
                    "as an unverified hypothesis until verified against backend source code.",
                ],
                is_ai_generated=False,
                diagnosis_source="rule_based_fallback (no LLM API key configured)",
            )

        elif bug_type == "SERVER_ERROR_5XX":
            return AIDiagnosis(
                hypothesis=(
                    f"The endpoint {finding.method} {finding.endpoint} crashed or encountered an unhandled "
                    f"exception resulting in HTTP {finding.actual_response.get('status_code', 500)}. "
                    "This typically indicates missing input validation, unhandled database errors, or uncaught null pointer exceptions."
                ),
                supporting_evidence=[
                    f"API returned HTTP {finding.actual_response.get('status_code', 500)} server error.",
                    "Expected 2xx success or graceful 4xx client error response.",
                ],
                additional_checks=[
                    "Inspect server stderr/stdout logs at the timestamp of execution.",
                    "Replay the request with varied input boundaries to identify the triggering payload property.",
                ],
                suggested_fix=(
                    "# Wrap the operation logic in a try-except block and return a structured 4xx error:\n"
                    "try:\n"
                    "    # Handler logic\n"
                    "    ...\n"
                    "except KeyError as exc:\n"
                    "    raise HTTPException(status_code=400, detail=f'Missing required parameter: {exc}')"
                ),
                remediation_explanation=(
                    "Implement comprehensive input validation and exception handling so that invalid client inputs "
                    "return HTTP 400 or 422 rather than crashing the server process."
                ),
                uncertainties=[
                    "Exact server stack trace was not visible in HTTP response headers.",
                ],
                is_ai_generated=False,
                diagnosis_source="rule_based_fallback (no LLM API key configured)",
            )

        else:
            # Generic schema mismatch diagnosis
            return AIDiagnosis(
                hypothesis=(
                    f"Endpoint {finding.method} {finding.endpoint} returned a response that violates its "
                    "documented OpenAPI specification schema contract."
                ),
                supporting_evidence=[
                    finding.explanation,
                ],
                additional_checks=[
                    "Check OpenAPI schema definition in openapi.json against response serializers.",
                ],
                suggested_fix=(
                    "# Update the Pydantic response model or API serializer to match the documented schema."
                ),
                remediation_explanation=(
                    "Ensure response serialization strictly complies with the OpenAPI contract types and required fields."
                ),
                uncertainties=[
                    "Verify whether the API implementation or the OpenAPI documentation is the intended source of truth.",
                ],
                is_ai_generated=False,
                diagnosis_source="rule_based_fallback (no LLM API key configured)",
            )


